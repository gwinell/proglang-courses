"""Embed exact production sources for the CLI-only Roblox model; no homework solution."""
from pathlib import Path
import hashlib, json

here = Path(__file__).resolve().parent
entries = []
hashes = {}
for name in ['GameRules.luau', 'World.luau', 'Main.server.luau']:
    data = (here.parent / name).read_bytes()
    hashes[name] = hashlib.sha256(data).hexdigest()
    source = data.decode('utf-8')
    assert ']====]' not in source
    entries.append(f'    ["{name}"] = [====[{source}]====],')
(here / 'Sources.luau').write_text('-- Generated by build_sources.py from the three adjacent project files.\nreturn {\n' + '\n'.join(entries) + '\n}\n')
(here / 'source_hashes.json').write_text(json.dumps(hashes, indent=2) + '\n')
print('Embedded three exact project files.')
